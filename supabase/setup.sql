create table if not exists public.library_owners (
 user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.library_owners enable row level security;
revoke all on public.library_owners from anon, authenticated;
grant select on public.library_owners to authenticated;
drop policy if exists owners_read_self on public.library_owners;
create policy owners_read_self on public.library_owners for select to authenticated using (user_id = (select auth.uid()));

create or replace function public.is_library_owner() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.library_owners where user_id = (select auth.uid())); $$;
revoke all on function public.is_library_owner() from public;
grant execute on function public.is_library_owner() to authenticated;

create table if not exists public.books (
 id text primary key,
 title text not null check (length(trim(title)) between 1 and 250),
 year integer not null check (year between 1900 and 2200),
 rating numeric(2,1) not null check (rating between 1 and 5 and mod(rating * 2, 1) = 0),
 format text not null check (format in ('print','audio')),
 category text not null default 'Literary & contemporary fiction' check (length(category) between 1 and 100),
 favorite boolean not null default false,
 notes text not null default '' check (length(notes) <= 10000)
);
alter table public.books enable row level security;
revoke all on public.books from anon, authenticated;
grant select on public.books to anon, authenticated;
grant insert, update, delete on public.books to authenticated;
drop policy if exists books_public_read on public.books;
create policy books_public_read on public.books for select to anon, authenticated using (true);
drop policy if exists books_owner_insert on public.books;
create policy books_owner_insert on public.books for insert to authenticated with check ((select public.is_library_owner()));
drop policy if exists books_owner_update on public.books;
create policy books_owner_update on public.books for update to authenticated using ((select public.is_library_owner())) with check ((select public.is_library_owner()));
drop policy if exists books_owner_delete on public.books;
create policy books_owner_delete on public.books for delete to authenticated using ((select public.is_library_owner()));

